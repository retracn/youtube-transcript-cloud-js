'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const fx = (f) => JSON.parse(fs.readFileSync(path.join(__dirname, 'fixtures', f), 'utf8'));
const plan = { dQw4w9WgXcQ: 'ok.json', xxxxxxxxxxx: 'no_de.json', nocaptions1: 'no_captions.json', gone1234567: 'unavailable.json' };
const calls = [];
function fakeFetch (url, init) {
  calls.push({ url, body: JSON.parse(init.body), auth: init.headers.Authorization });
  if (init.headers.Authorization !== 'Bearer good') return Promise.resolve({ ok: false, status: 401, json: async () => ({}) });
  const rows = JSON.parse(init.body).videos.flatMap((v) => fx(plan[v]));
  return Promise.resolve({ ok: true, status: 201, json: async () => rows });
}
const cfg = (extra) => Object.assign({ fetch: fakeFetch, apifyToken: 'good' }, extra);

const yt = require('..');

test('same output shape as youtube-transcript 1.3 (milliseconds)', async () => {
  const t = await yt.YoutubeTranscript.fetchTranscript('https://www.youtube.com/watch?v=dQw4w9WgXcQ', cfg({ lang: 'en' }));
  assert.strictEqual(t.length, 61);
  assert.deepStrictEqual(t[0], { text: '[♪♪♪]', duration: 1680, offset: 1360, lang: 'en' });
  assert.deepStrictEqual(calls.at(-1).body, { videos: ['dQw4w9WgXcQ'], language: 'en', includeTimestamps: true, includeAutoGenerated: true, maxVideosPerChannel: 1 });
  const viaFn = await yt.fetchTranscript('dQw4w9WgXcQ', cfg());
  assert.strictEqual(viaFn.length, 61);
});

test('video ID parsing matches the original and adds Shorts and live URLs', async () => {
  for (const u of ['https://youtu.be/dQw4w9WgXcQ', 'https://www.youtube.com/embed/dQw4w9WgXcQ', 'https://www.youtube.com/shorts/dQw4w9WgXcQ', 'https://m.youtube.com/watch?feature=share&v=dQw4w9WgXcQ']) {
    await yt.fetchTranscript(u, cfg());
    assert.deepStrictEqual(calls.at(-1).body.videos, ['dQw4w9WgXcQ'], u);
  }
  const n = calls.length;
  await assert.rejects(yt.fetchTranscript('definitely not a video', cfg()), (e) => e instanceof yt.YoutubeTranscriptError && /Impossible to retrieve Youtube video ID/.test(e.message));
  assert.strictEqual(calls.length, n, 'no request for an invalid ID');
});

test('errors map to the original classes and messages', async () => {
  await assert.rejects(yt.fetchTranscript('nocaptions1', cfg()), (e) => e instanceof yt.YoutubeTranscriptDisabledError && e.message === '[YoutubeTranscript] 🚨 Transcript is disabled on this video (nocaptions1)');
  await assert.rejects(yt.fetchTranscript('gone1234567', cfg()), yt.YoutubeTranscriptVideoUnavailableError);
  await assert.rejects(yt.fetchTranscript('xxxxxxxxxxx', cfg({ lang: 'de' })), (e) => e instanceof yt.YoutubeTranscriptNotAvailableLanguageError && /Available languages: en, fr/.test(e.message));
  await assert.rejects(yt.fetchTranscript('xxxxxxxxxxx', cfg()), yt.YoutubeTranscriptNotAvailableError);
  await assert.rejects(yt.fetchTranscript('dQw4w9WgXcQ', cfg({ lang: 'fr' })), (e) => e instanceof yt.YoutubeTranscriptNotAvailableLanguageError && /en, de-DE, ja/.test(e.message), 'a fallback language is not returned when lang was asked');
  const ok = await yt.fetchTranscript('dQw4w9WgXcQ', cfg({ lang: 'en-GB' }));
  assert.strictEqual(ok.length, 61, 'en-GB matches an en transcript');
});

test('token problems are clear', async () => {
  await assert.rejects(yt.fetchTranscript('dQw4w9WgXcQ', { fetch: fakeFetch, apifyToken: 'bad' }), /Apify rejected the API token/);
  const saved = process.env.APIFY_TOKEN;
  delete process.env.APIFY_TOKEN; delete process.env.APIFY_API_TOKEN;
  await assert.rejects(yt.fetchTranscript('dQw4w9WgXcQ', { fetch: fakeFetch }), /No Apify API token/);
  if (saved) process.env.APIFY_TOKEN = saved;
});

test('fetchTranscripts: many videos in one request', async () => {
  const n = calls.length;
  const out = await yt.YoutubeTranscript.fetchTranscripts(['dQw4w9WgXcQ', 'gone1234567'], cfg());
  assert.strictEqual(calls.length, n + 1);
  assert.strictEqual(out.dQw4w9WgXcQ.length, 61);
  assert.ok(out.gone1234567 instanceof yt.YoutubeTranscriptVideoUnavailableError);
});

test('ESM import exposes the same API', async () => {
  const esm = await import('../index.mjs');
  assert.strictEqual(esm.YoutubeTranscript, yt.YoutubeTranscript);
  assert.strictEqual(typeof esm.fetchTranscript, 'function');
  assert.strictEqual(esm.default.YoutubeTranscriptDisabledError, yt.YoutubeTranscriptDisabledError);
});
