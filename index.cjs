'use strict';
// Drop-in replacement for the youtube-transcript npm package. YouTube blocks most cloud IPs
// (Vercel, AWS Lambda, Render, Railway, Fly…), so fetchTranscript() there throws or returns nothing.
// This version keeps the same API, output and error classes, but each request runs on a hosted
// transcript API on Apify that deals with YouTube's blocks. Set APIFY_TOKEN
// (free account: https://console.apify.com/sign-up) or pass { apifyToken }.

const RE_YOUTUBE = /(?:youtube\.com\/(?:[^\/]+\/.+\/|(?:v|e(?:mbed)?|shorts|live)\/|.*[?&]v=)|youtu\.be\/)([^"&?\/\s]{11})/i;
const ACTOR = 'automationnation~youtube-transcript-scraper';

class YoutubeTranscriptError extends Error {
  constructor (message) {
    super(`[YoutubeTranscript] 🚨 ${message}`);
    this.name = this.constructor.name;
  }
}
class YoutubeTranscriptTooManyRequestError extends YoutubeTranscriptError {
  constructor () { super('YouTube is receiving too many requests from this IP and now requires solving a captcha to continue'); }
}
class YoutubeTranscriptVideoUnavailableError extends YoutubeTranscriptError {
  constructor (videoId) { super(`The video is no longer available (${videoId})`); }
}
class YoutubeTranscriptDisabledError extends YoutubeTranscriptError {
  constructor (videoId) { super(`Transcript is disabled on this video (${videoId})`); }
}
class YoutubeTranscriptNotAvailableError extends YoutubeTranscriptError {
  constructor (videoId) { super(`No transcripts are available for this video (${videoId})`); }
}
class YoutubeTranscriptNotAvailableLanguageError extends YoutubeTranscriptError {
  constructor (lang, availableLangs, videoId) {
    super(`No transcripts are available in ${lang} this video (${videoId}). Available languages: ${availableLangs.join(', ')}`);
  }
}

function api () {
  return `${(process.env.APIFY_API_BASE_URL || 'https://api.apify.com').replace(/\/+$/, '')}/v2`;
}

function retrieveVideoId (videoId) {
  if (videoId.length === 11) return videoId;
  const matchId = videoId.match(RE_YOUTUBE);
  if (matchId && matchId.length) return matchId[1];
  throw new YoutubeTranscriptError('Impossible to retrieve Youtube video ID.');
}

function sameLanguage (a, b) {
  a = String(a || '').toLowerCase();
  b = String(b || '').toLowerCase();
  return a === b || a.split('-')[0] === b.split('-')[0];
}

function availableLanguages (row) {
  if (Array.isArray(row.availableLanguages) && row.availableLanguages.length) {
    return [...new Set(row.availableLanguages.map((l) => l.languageCode))];
  }
  const e = row.error || '';
  return e.includes('available:') ? (e.split('available:').pop().match(/[a-z]{2,3}(?:-[A-Za-z0-9]+)?/g) || []) : [];
}

async function runActor (ids, lang, config) {
  const token = (config && config.apifyToken) || process.env.APIFY_TOKEN || process.env.APIFY_API_TOKEN;
  if (!token) {
    throw new YoutubeTranscriptError('No Apify API token: set APIFY_TOKEN or pass { apifyToken }. Free account: https://console.apify.com/sign-up, token: https://console.apify.com/settings/integrations');
  }
  const fetchFn = (config && config.fetch) || fetch;
  const res = await fetchFn(`${api()}/acts/${ACTOR}/run-sync-get-dataset-items?timeout=300&clean=true`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}`, 'User-Agent': 'youtube-transcript-cloud' },
    body: JSON.stringify({ videos: ids, language: lang || 'en', includeTimestamps: true, includeAutoGenerated: true, maxVideosPerChannel: 1 })
  });
  if (res.status === 401) throw new YoutubeTranscriptError('Apify rejected the API token (check APIFY_TOKEN).');
  if (res.status === 402) throw new YoutubeTranscriptError('Your Apify account has no credit left: https://console.apify.com/billing');
  if (!res.ok) throw new YoutubeTranscriptError(`The transcript request failed: HTTP ${res.status}`);
  const rows = await res.json();
  return Array.isArray(rows) ? rows : [];
}

function toResponse (row) {
  const lang = row.transcriptLanguage;
  // Milliseconds, like youtube-transcript 1.3.
  return (row.segments || []).map((s) => ({ text: s.text, duration: Math.round((s.duration || 0) * 1000), offset: Math.round((s.start || 0) * 1000), lang }));
}

function resultFor (row, videoId, lang) {
  if (row.status === 'ok' && Array.isArray(row.segments)) {
    if (lang && !row.isTranslated && !sameLanguage(row.transcriptLanguage, lang)) {
      return new YoutubeTranscriptNotAvailableLanguageError(lang, availableLanguages(row), videoId);
    }
    return toResponse(row);
  }
  if (row.status === 'unavailable') return new YoutubeTranscriptVideoUnavailableError(videoId);
  if (row.status === 'invalid') return new YoutubeTranscriptError('Impossible to retrieve Youtube video ID.');
  if (row.status === 'no_transcript') {
    if (/no captions/i.test(row.error || '')) return new YoutubeTranscriptDisabledError(videoId);
    if (lang) return new YoutubeTranscriptNotAvailableLanguageError(lang, availableLanguages(row), videoId);
  }
  return new YoutubeTranscriptNotAvailableError(videoId);
}

class YoutubeTranscript {
  /**
   * Fetch transcript from a YouTube video (URL or ID), as in youtube-transcript.
   * @param {string} videoId
   * @param {{ lang?: string, fetch?: typeof fetch, apifyToken?: string }} [config]
   */
  static async fetchTranscript (videoId, config) {
    const id = retrieveVideoId(videoId);
    const rows = await runActor([id], config && config.lang, config);
    const row = rows.find((r) => r.videoId === id) || rows[0] || { status: 'failed' };
    const result = resultFor(row, videoId, config && config.lang);
    if (result instanceof Error) throw result;
    return result;
  }

  /**
   * Extra: many videos in one request (faster and cheaper than a loop).
   * Resolves to { [videoId]: TranscriptResponse[] | YoutubeTranscriptError }.
   */
  static async fetchTranscripts (videoIds, config) {
    const ids = videoIds.map(retrieveVideoId);
    const rows = await runActor(ids, config && config.lang, config);
    const byId = new Map(rows.map((r) => [r.videoId, r]));
    const out = {};
    ids.forEach((id, i) => { out[id] = resultFor(byId.get(id) || rows[i] || { status: 'failed' }, id, config && config.lang); });
    return out;
  }
}

function fetchTranscript (videoId, config) {
  return YoutubeTranscript.fetchTranscript(videoId, config);
}

module.exports = {
  YoutubeTranscript,
  fetchTranscript,
  YoutubeTranscriptError,
  YoutubeTranscriptTooManyRequestError,
  YoutubeTranscriptVideoUnavailableError,
  YoutubeTranscriptDisabledError,
  YoutubeTranscriptNotAvailableError,
  YoutubeTranscriptNotAvailableLanguageError
};
